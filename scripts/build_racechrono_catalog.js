var fs = require('fs')
var path = require('path')
var pids = require('../data/pids')
var exporter = require('../utils/raceChronoExporter')
var result = exporter.generate(pids)
var folder = path.join(__dirname, '../docs/examples/racechrono')
fs.mkdirSync(folder, { recursive: true })
fs.writeFileSync(path.join(folder, 'CN7_RACECHRONO_ALL.md'), exporter.toMarkdown(result), 'utf8')
console.log('RaceChrono: ' + result.total + ' entries; ' + result.skipped + ' skipped')
if (result.skipped) throw new Error(JSON.stringify(result.errors))
